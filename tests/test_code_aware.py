"""Tests for code-aware cleaning (identifiers preserved, comments cleaned)."""
from pathlib import Path

from ai_untell.cleaner import Cleaner
from ai_untell.code_aware.extractors import extract_segments, get_spec
from ai_untell.code_aware.languages import detect_content_kind, detect_language
from ai_untell.code_aware.markdown import split_markdown
from ai_untell.types import Config, ContentKind, LanguageId


def test_detect_python_from_extension():
    assert detect_language("x = 1", Path("foo.py")) == LanguageId.PYTHON


def test_detect_python_from_content():
    code = "import os\nfrom sys import argv\n\ndef main():\n    pass\n"
    assert detect_language(code) == LanguageId.PYTHON


def test_detect_go_from_content():
    code = "package main\n\nfunc main() {}\n"
    assert detect_language(code) == LanguageId.GO


def test_content_kind_code():
    code = "import os\nimport sys\n\ndef f():\n    return 1\n"
    assert detect_content_kind(code) == ContentKind.CODE


def test_content_kind_mixed():
    text = "# Title\n\n```python\nx = 1\n```\n"
    assert detect_content_kind(text) == ContentKind.MIXED


def test_python_segments_extraction():
    code = '# comment\nx = "string value"\n'
    spec = get_spec(LanguageId.PYTHON)
    segs = extract_segments(code, spec)
    kinds = [s.kind for s in segs]
    assert "line_comment" in kinds
    assert "string" in kinds


def test_python_docstring_extraction():
    code = 'def f():\n    """Docstring text."""\n    return 1\n'
    spec = get_spec(LanguageId.PYTHON)
    segs = extract_segments(code, spec)
    docstrings = [s for s in segs if s.kind == "docstring"]
    assert any("Docstring" in code[s.content_start:s.content_end] for s in docstrings)


def test_js_block_comment_extraction():
    code = "/* block comment */\nlet x = 'a';\n"
    spec = get_spec(LanguageId.JAVASCRIPT)
    segs = extract_segments(code, spec)
    assert any(s.kind == "block_comment" for s in segs)


def test_code_identifiers_preserved(ai_code):
    result = Cleaner(Config(synonym_strength="moderate")).clean(
        ai_code, path=Path("claude_generated.py")
    )
    out = result.cleaned
    # Identifiers must survive untouched.
    assert "def load_config" in out
    assert "def merge_configs" in out
    assert "json.loads(data)" in out
    assert "{**base, **override}" in out


def test_generated_by_line_removed(ai_code):
    result = Cleaner().clean(ai_code, path=Path("claude_generated.py"))
    assert "Generated by Claude" not in result.cleaned


def test_docstring_dash_cleaned(ai_code):
    result = Cleaner().clean(ai_code, path=Path("claude_generated.py"))
    out = result.cleaned
    assert "\u2014" not in out


def test_markdown_split_segments():
    text = "Prose here.\n\n```python\nx = 1\n```\n\nMore prose.\n"
    segments = split_markdown(text)
    kinds = [s.kind for s in segments]
    assert "prose" in kinds
    assert "code_block" in kinds


def test_mixed_code_fence_not_broken(mixed_doc):
    result = Cleaner(Config(synonym_strength="moderate")).clean(
        mixed_doc, path=Path("notes.md")
    )
    out = result.cleaned
    assert "def greet" in out
    assert "return f\"Hello, {name}\"" in out
